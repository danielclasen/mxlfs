#!/bin/sh
# Write .agents/skills/desloppify/SKILL.md from the desloppify release pinned
# below. The skill is the shared body and one overlay per harness that ship
# inside the release's wheel, the documents `desloppify setup` installs from,
# with a section on running desloppify in this repository after the
# frontmatter. `desloppify update-skill` is not used: it fetches the skill
# from the tool's main branch, not from a release, so its output changes
# without a version change.
#
# To move to another release, set VERSION and SHA256 to its wheel's version
# and the sha256 PyPI lists for it, run this script, and commit both.
# Needs curl, sha256sum and python3.
set -eu
VERSION=1.0
SHA256=77d8bcfacd21edb8efc064fd94ab3adec7221f5efff192b7a2a0f0c55564f007
WHEEL=desloppify-$VERSION-py3-none-any.whl
# The harnesses whose overlays follow the shared body.
OVERLAYS="CLAUDE CODEX COPILOT GEMINI OPENCODE"

cd "$(dirname "$0")/.."
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
url=$(curl -fsSL "https://pypi.org/pypi/desloppify/$VERSION/json" |
  python3 -I -c 'import json, sys
for f in json.load(sys.stdin)["urls"]:
    if f["filename"] == sys.argv[1]:
        print(f["url"])' "$WHEEL")
[ -n "$url" ] || { echo "PyPI lists no $WHEEL" >&2; exit 1; }
curl -fsSL -o "$work/$WHEEL" "$url"
echo "$SHA256  $work/$WHEEL" | sha256sum -c - >/dev/null
python3 -I -m zipfile -e "$work/$WHEEL" "$work/wheel"
data=$work/wheel/desloppify/data/global

# Upstream's text in ASCII: the bytes are the UTF-8 encodings of dashes,
# arrows, typographic quotes, the ellipsis and the no-break space.
ascii() {
  LC_ALL=C sed \
    -e "s/$(printf '\342\200\224')/--/g" \
    -e "s/$(printf '\342\200\223')/-/g" \
    -e "s/$(printf '\342\206\222')/->/g" \
    -e "s/$(printf '\342\206\220')/<-/g" \
    -e "s/$(printf '\342\206\224')/<->/g" \
    -e "s/$(printf '\342\200\230')/'/g" \
    -e "s/$(printf '\342\200\231')/'/g" \
    -e "s/$(printf '\342\200\234')/\"/g" \
    -e "s/$(printf '\342\200\235')/\"/g" \
    -e "s/$(printf '\342\200\246')/.../g" \
    -e "s/$(printf '\302\240')/ /g"
}

repo_section() {
  cat <<EOF
<!-- Generated by dev/desloppify-skill.sh from desloppify $VERSION. Edit that
script, not this file. -->

## In this repository

- Run the pinned release, not whatever the Prerequisite section at the end
  of the shared part installs. Here and in the shared part, \`desloppify\`
  stands for \`uvx --from 'desloppify[full]==$VERSION' desloppify\`, or a
  \`desloppify\` on PATH whose \`desloppify --version\` reports $VERSION.
- Scan from the checkout root with \`--path .\` and \`--no-badge\`, so no
  \`scorecard.png\` is written. Scan state lives in \`.desloppify/\`. Both
  are gitignored and never committed.
- desloppify reads no \`.gitignore\`. Before the first scan, exclude what git
  ignores and the worktrees:

  \`\`\`sh
  git ls-files --others --ignored --exclude-standard --directory |
    while IFS= read -r p; do desloppify exclude "\$p"; done
  desloppify exclude .claude/worktrees/
  \`\`\`
- Branches, commits and pull requests follow AGENTS.md, not the examples
  below. Do not run \`desloppify config set commit_pr\`,
  \`desloppify plan commit-log record\` or anything else that edits a pull
  request description or a commit message.
- Do not run \`desloppify update-skill\` or \`desloppify setup\`: the first
  replaces this file with an unpinned one, the second installs skills into
  the home directory.
- Report a fault in desloppify to the user rather than opening an issue or
  pull request upstream.
- The shared part is followed by one overlay per harness, each under its own
  heading. Follow the overlay of the harness running the session. A
  reference to \`docs/<HARNESS>.md\` means that overlay.
EOF
}

out=.agents/skills/desloppify/SKILL.md
end=$(awk 'NR > 1 && $0 == "---" { print NR; exit }' "$data/SKILL.md")
[ "$(sed -n 1p "$data/SKILL.md")" = --- ] && [ -n "$end" ] ||
  { echo "$data/SKILL.md has no frontmatter" >&2; exit 1; }
mkdir -p "$(dirname "$out")"
{
  sed -n "1,${end}p" "$data/SKILL.md" | ascii
  printf '\n'
  repo_section
  printf '\n%s\n' "$(sed "1,${end}d" "$data/SKILL.md" | sed '/./,$!d' | ascii)"
  for o in $OVERLAYS; do
    [ -f "$data/$o.md" ] || { echo "desloppify $VERSION ships no $o overlay" >&2; exit 1; }
    printf '\n%s\n' "$(ascii < "$data/$o.md")"
  done
} > "$work/SKILL.md"
line=$(LC_ALL=C grep -n "$(printf '[^\t -~]')" "$work/SKILL.md" | head -1 | cut -d: -f1)
[ -z "$line" ] || { echo "line $line of the skill is not ASCII; add its character to ascii()" >&2; exit 1; }
cp "$work/SKILL.md" "$out"
echo "$out from desloppify $VERSION"
